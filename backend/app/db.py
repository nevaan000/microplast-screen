def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def connect() -> psycopg.Connection:
    if not config.database_url:
        raise RuntimeError(
            "DATABASE_URL is not set. MicroPlast Screen keeps every record in Postgres; "
            "point DATABASE_URL at a local server or a Neon branch."
        )
    return psycopg.connect(
        config.database_url,
        row_factory=dict_row,
        connect_timeout=15,
        # Serverless Postgres is reached through a transaction-mode pooler, which
        # hands each transaction a different backend; a prepared statement from an
        # earlier transaction would not exist there.
        prepare_threshold=None,
    )


@contextmanager
def database() -> Iterator[psycopg.Connection]:
    connection = connect()
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def initialize_database() -> None:
    with database() as conn:
        for statement in SCHEMA_STATEMENTS:
            conn.execute(statement)
        for key, value in DEFAULT_SETTINGS.items():
            conn.execute(
                "INSERT INTO settings(key, value_json) VALUES (%s, %s) ON CONFLICT (key) DO NOTHING",
                (key, json.dumps(value)),
            )


def get_settings() -> dict[str, Any]:
    with database() as conn:
        rows = conn.execute("SELECT key, value_json FROM settings").fetchall()
    values = DEFAULT_SETTINGS.copy()
    values.update({row["key"]: json.loads(row["value_json"]) for row in rows if row["key"] in DEFAULT_SETTINGS})
    return values


def update_settings(values: dict[str, Any]) -> dict[str, Any]:
    allowed = set(DEFAULT_SETTINGS)
    with database() as conn:
        for key, value in values.items():
            if key in allowed:
                conn.execute(
                    "INSERT INTO settings(key, value_json) VALUES (%s, %s) "
                    "ON CONFLICT (key) DO UPDATE SET value_json = excluded.value_json",
                    (key, json.dumps(value)),
                )
    return get_settings()


def reset_settings() -> dict[str, Any]:
    with database() as conn:
        conn.execute("DELETE FROM settings")
        for key, value in DEFAULT_SETTINGS.items():
            conn.execute("INSERT INTO settings(key, value_json) VALUES (%s, %s)", (key, json.dumps(value)))
    return get_settings()


def active_calibration() -> dict[str, Any] | None:
    with database() as conn:
        return conn.execute("SELECT * FROM calibrations WHERE is_active = 1 ORDER BY id DESC LIMIT 1").fetchone()
